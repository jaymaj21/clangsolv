#!/usr/bin/env python3
"""Generate ClangSOLV vocabulary metadata from application-owned properties."""
import argparse
from pathlib import Path
import re
import sys

KEYWORDS = set('alignas alignof and and_eq asm auto bitand bitor bool break case catch char char16_t char32_t class compl const constexpr const_cast continue decltype default delete do double dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new noexcept not not_eq nullptr operator or or_eq private protected public register reinterpret_cast return short signed sizeof static static_assert static_cast struct switch template this thread_local throw true try typedef typeid typename union unsigned using virtual void volatile wchar_t while xor xor_eq concept requires co_await co_return co_yield consteval constinit char8_t'.split())

def identifier(value):
    if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*',value) or '__' in value or value in KEYWORDS:
        raise ValueError(f'invalid or reserved C++ identifier: {value!r}')
    return value

def render(config):
    properties={}
    for number,line in enumerate(config.splitlines(),1):
        line=line.strip()
        if not line or line.startswith(('#','!')): continue
        if '=' not in line: raise ValueError(f'line {number}: expected key=value')
        key,value=(part.strip() for part in line.split('=',1))
        if key not in ('namespace','labels') or key in properties:
            raise ValueError(f'line {number}: unknown or repeated key {key!r}')
        properties[key]=value
    if set(properties)!={'namespace','labels'}: raise ValueError('configuration requires namespace and labels')
    namespace='::'.join(identifier(part) for part in properties['namespace'].split('::'))
    if namespace.split('::')[0] in ('std','clangsolv'): raise ValueError('choose an application-owned namespace')
    labels=[identifier(part.strip()) for part in properties['labels'].split(',')]
    if len(set(labels))!=len(labels): raise ValueError('duplicate label')
    declarations='\n'.join(f'struct CLANGSOLV_ANNOTATE("clangsolv.label") {name} {{}};' for name in labels)
    return f'// Generated by ClangSOLV; edit the properties file.\n#pragma once\n#include <clangsolv/annotations.hpp>\n\nnamespace {namespace} {{\n{declarations}\n}}\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    try:
        content=render(args.config.read_text(encoding='utf-8-sig'))
        args.output.parent.mkdir(parents=True,exist_ok=True)
        if not args.output.exists() or args.output.read_text(encoding='utf-8')!=content:
            args.output.write_text(content,encoding='utf-8',newline='\n')
    except (OSError,ValueError) as error:
        print(f'ClangSOLV: {error}',file=sys.stderr)
        return 2
    return 0

if __name__=='__main__': sys.exit(main())
